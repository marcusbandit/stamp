"""Draw the Stamp logo, a globe cut into cells with three of them marked, and write every
form of it the app and the store need:

  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive icon, colour layer
  app/src/main/res/drawable/ic_launcher_monochrome.xml   adaptive icon, themed-icon layer
  docs/logo.svg                                          the mark on its own
  fastlane/.../images/icon.png                           512 px store icon (needs resvg)
  fastlane/.../images/featureGraphic.png                 1024 x 500 store banner (needs resvg)

The cells mirror the map: grey land, and one cell each in the visited, lived and want-to-go
colours. Run from the repo root:  python3 -I tools/build_icon.py
"""
import os
import shutil
import subprocess
import sys
import tempfile

INK = "#14171B"
LAND = "#2C3139"
VISITED = "#20C997"
LIVED = "#748FFC"
WANT = "#FCC419"

# Geometry in the 108 x 108 adaptive-icon viewport. Launchers show the middle 72 and keep the
# middle 66 safe from masks, so the globe stays inside a radius of 27.
CX = CY = 54.0
R = 27.0
MERIDIAN_RX = 11.7   # half-width of the middle column, an ellipse from pole to pole
BAND = 10.8          # half-height of the middle band
GAP = 2.3            # width of the cut between cells

# (column, band) -> colour; columns and bands are 0, 1, 2 from left and from the top.
MARKED = {(1, 1): VISITED, (0, 0): LIVED, (2, 2): WANT}


def f(v):
    return ("%.3f" % v).rstrip("0").rstrip(".")


def ellipse(rx, ry, cw=True):
    s = 1 if cw else 0
    return (f"M{f(CX - rx)},{f(CY)} A{f(rx)},{f(ry)} 0 1 {s} {f(CX + rx)},{f(CY)} "
            f"A{f(rx)},{f(ry)} 0 1 {s} {f(CX - rx)},{f(CY)} Z")


def rect(x0, y0, x1, y1):
    return f"M{f(x0)},{f(y0)} H{f(x1)} V{f(y1)} H{f(x0)} Z"


H = GAP / 2
OUT = R + 2  # anything past the rim; the globe itself is the shape that gets clipped


def column(i):
    """Clip for column i. The side columns run from the edge of the middle ellipse outwards,
    one half of the ellipse as their inner side."""
    if i == 1:
        return ellipse(MERIDIAN_RX - H, R + 1)
    rx, ry = MERIDIAN_RX + H, R + 1
    side = -1 if i == 0 else 1
    sweep = 0 if i == 0 else 1
    return (f"M{f(CX)},{f(CY - ry)} A{f(rx)},{f(ry)} 0 0 {sweep} {f(CX)},{f(CY + ry)} "
            f"L{f(CX)},{f(CY + OUT)} L{f(CX + side * OUT)},{f(CY + OUT)} "
            f"L{f(CX + side * OUT)},{f(CY - OUT)} L{f(CX)},{f(CY - OUT)} Z")


def band(j):
    edges = [CY - OUT, CY - BAND, CY + BAND, CY + OUT]
    top = edges[j] + (H if j > 0 else 0)
    bottom = edges[j + 1] - (H if j < 2 else 0)
    return rect(CX - OUT, top, CX + OUT, bottom)


GLOBE = ellipse(R, R)


def cells(mono):
    """Yields (column clip, band clip, colour, alpha) for the nine cells."""
    for j in range(3):
        for i in range(3):
            colour = MARKED.get((i, j))
            if mono:
                yield column(i), band(j), "#FFFFFF", 1.0 if colour else 0.38
            else:
                yield column(i), band(j), colour or LAND, 1.0


def vector(mono):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by tools/build_icon.py. Edit that, not this. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp"', '    android:height="108dp"',
           '    android:viewportWidth="108"', '    android:viewportHeight="108">']
    for col, bnd, colour, alpha in cells(mono):
        out += ["    <group>",
                f'        <clip-path android:pathData="{col}" />',
                "        <group>",
                f'            <clip-path android:pathData="{bnd}" />',
                "            <path",
                f'                android:fillColor="{colour}"']
        if alpha < 1:
            out.append(f'                android:fillAlpha="{f(alpha)}"')
        out += [f'                android:pathData="{GLOBE}" />',
                "        </group>", "    </group>"]
    out.append("</vector>")
    return "\n".join(out) + "\n"


def svg_mark(prefix="c"):
    """The mark as SVG elements in the 108 viewport, with unique clip ids."""
    defs, body = [], []
    for n, (col, bnd, colour, _) in enumerate(cells(False)):
        defs.append(f'<clipPath id="{prefix}c{n}"><path d="{col}"/></clipPath>'
                    f'<clipPath id="{prefix}b{n}"><path d="{bnd}"/></clipPath>')
        body.append(f'<g clip-path="url(#{prefix}c{n})"><g clip-path="url(#{prefix}b{n})">'
                    f'<path d="{GLOBE}" fill="{colour}"/></g></g>')
    return "<defs>" + "".join(defs) + "</defs>" + "".join(body)


def svg_logo():
    # The mark alone, cropped to the globe with a little air.
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="25 25 58 58" width="580" height="580">'
            + svg_mark() + "</svg>\n")


def svg_store_icon():
    # Play masks the 512 icon itself, so this is a full square: ink with the mark at icon scale.
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="512" height="512">'
            f'<rect x="0" y="0" width="108" height="108" fill="{INK}"/>' + svg_mark() + "</svg>\n")


def svg_feature_graphic():
    # 1024 x 500: the mark on the left, the name beside it. Play may crop the edges, so the
    # content stays in the middle.
    s = 5.0  # 108-unit mark scaled up; globe diameter 54 -> 270 px
    gx, gy = 300, 250
    mark = (f'<g transform="translate({f(gx - CX * s)} {f(gy - CY * s)}) scale({s})">'
            + svg_mark("f") + "</g>")
    text = ('<text x="470" y="282" font-family="Adwaita Sans, Inter, Roboto, sans-serif" '
            'font-weight="800" font-size="118" letter-spacing="-3" fill="#E6E9ED">Stamp</text>')
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 500" width="1024" height="500">'
            f'<rect width="1024" height="500" fill="{INK}"/>' + mark + text + "</svg>\n")


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(path)


def render(svg_text, png_path, width, height):
    resvg = shutil.which("resvg")
    if not resvg:
        print("resvg not found, skipping " + png_path, file=sys.stderr)
        return
    os.makedirs(os.path.dirname(png_path), exist_ok=True)
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as tmp:
        tmp.write(svg_text)
    try:
        subprocess.run([resvg, "-w", str(width), "-h", str(height), tmp.name, png_path], check=True)
    finally:
        os.unlink(tmp.name)
    print(png_path)


def main():
    res = "app/src/main/res/drawable"
    store = "fastlane/metadata/android/en-US/images"
    write(f"{res}/ic_launcher_foreground.xml", vector(mono=False))
    write(f"{res}/ic_launcher_monochrome.xml", vector(mono=True))
    write("docs/logo.svg", svg_logo())
    render(svg_store_icon(), f"{store}/icon.png", 512, 512)
    render(svg_feature_graphic(), f"{store}/featureGraphic.png", 1024, 500)


if __name__ == "__main__":
    main()
